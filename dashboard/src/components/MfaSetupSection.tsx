import { FormEvent, useState } from 'react';
import { ShieldCheck } from 'lucide-react';
import { api, ApiError, MfaSetupStart, MfaStatus } from '../lib/api';
import { Badge, Card } from './ui';

/**
 * Settings → Multi-factor login: the logged-in admin or doctor sets up their
 * own authenticator app here (owner, 24 Nov 2026: not at the login screen).
 * Once set up, every login asks for the app code after the PIN.
 */
export function MfaSetupSection({ status, onChanged }: { status: MfaStatus | null; onChanged: () => void }) {
  const [setup, setSetup] = useState<MfaSetupStart | null>(null);
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [done, setDone] = useState(false);

  if (!status?.available) return null;

  async function begin(): Promise<void> {
    if (status?.setUp && !confirm('Set up the authenticator app again (for example on a new phone)?\n\nThe old ACISI entry in your app stops working once you finish.')) return;
    setBusy(true);
    setError(null);
    setDone(false);
    try {
      setSetup(await api.startMfaSetup());
      setCode('');
    } catch (err) {
      setError(err instanceof ApiError ? err.message : 'Could not start the setup. Try again.');
    } finally {
      setBusy(false);
    }
  }

  async function confirmCode(e: FormEvent): Promise<void> {
    e.preventDefault();
    if (!setup) return;
    setBusy(true);
    setError(null);
    try {
      await api.confirmMfaSetup(setup.setupId, code);
      setSetup(null);
      setDone(true);
      onChanged();
    } catch (err) {
      const message = err instanceof ApiError ? err.message : 'Something went wrong. Try again.';
      setError(message);
      if (/start again|expired/i.test(message)) setSetup(null);
    } finally {
      setBusy(false);
    }
  }

  return (
    <Card
      title="Multi-factor login"
      icon={ShieldCheck}
      actions={status.setUp ? <Badge tone="success">On</Badge> : <Badge tone="warning">Not set up</Badge>}
    >
      {!setup && (
        <>
          <p className="mb-4 text-sm text-ink-500">
            {status.setUp
              ? 'Your logins are protected: after your PIN, you type the 6-digit code from your authenticator app. If you change phones, set it up again here.'
              : 'Protect your login with a 6-digit code from an authenticator app on your phone (Google Authenticator or Microsoft Authenticator, free). It takes about 2 minutes. After this, each login asks for the code after your PIN.'}
          </p>
          {done && (
            <p role="status" className="mb-3 rounded-xl border border-green-200 bg-green-50 px-3.5 py-2.5 text-sm text-green-800">
              Done. Next time you log in, type the code from the app after your PIN.
            </p>
          )}
          <button type="button" onClick={() => void begin()} disabled={busy} className="btn-gold min-h-11 px-5 py-2.5 text-sm">
            {busy ? 'Starting…' : status.setUp ? 'Set up again (new phone)' : 'Set up authenticator app'}
          </button>
        </>
      )}

      {setup && (
        <form onSubmit={(e) => void confirmCode(e)} className="space-y-4">
          <ol className="list-decimal space-y-1 pl-5 text-sm text-navy-900">
            <li>On your own phone, install Google Authenticator or Microsoft Authenticator (free).</li>
            <li>In the app, tap + and scan this QR code.</li>
            <li>Type the 6-digit code the app shows for ACISI below.</li>
          </ol>
          {/* SVG generated by the server's qrcode library from a random secret: no user content. */}
          <div
            className="mx-auto w-48 rounded-lg border border-slate-200 bg-white p-2"
            aria-label="QR code for your authenticator app"
            role="img"
            dangerouslySetInnerHTML={{ __html: setup.qrCodeSvg }}
          />
          <p className="text-xs text-ink-500">
            Using ACISI on this same phone, so you can&apos;t scan? In the app choose &quot;Enter a setup key&quot;: account{' '}
            <span className="font-mono">{setup.accountName}</span>, key <span className="select-all break-all font-mono text-navy-900">{setup.secret}</span>{' '}
            (time based).
          </p>
          <div>
            <label className="mb-1.5 block text-sm font-medium text-navy-900" htmlFor="mfaSetupCode">
              Code from the app
            </label>
            <input
              id="mfaSetupCode"
              type="text"
              inputMode="numeric"
              autoComplete="one-time-code"
              pattern="[0-9]{6}"
              maxLength={6}
              required
              value={code}
              onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
              className="min-h-12 w-full max-w-xs rounded-xl border border-slate-300 bg-white px-3.5 py-3 text-center font-mono text-2xl tracking-[0.5em] text-navy-900 focus:border-gold-500 focus:outline-none"
            />
          </div>
          {error && (
            <p role="alert" className="rounded-xl border border-red-200 bg-red-50 px-3.5 py-2.5 text-sm text-red-700">
              {error}
            </p>
          )}
          <div className="flex flex-wrap items-center gap-3">
            <button type="submit" disabled={busy || code.length !== 6} className="btn-gold min-h-11 px-5 py-2.5 text-sm">
              {busy ? 'Checking…' : 'Turn on'}
            </button>
            <button type="button" onClick={() => setSetup(null)} className="text-sm font-semibold text-gold-700 underline underline-offset-2">
              Cancel
            </button>
          </div>
          <p className="text-xs text-ink-500">If you lose or change your phone, ask your clinic admin to reset your authenticator app.</p>
        </form>
      )}

      {!setup && error && (
        <p role="alert" className="mt-3 text-sm text-red-700">
          {error}
        </p>
      )}
    </Card>
  );
}
